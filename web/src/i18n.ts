export function translate(locale: Locale, key: Key, values?: Record<string, string | number>): string {
  let result = (locale === 'en-US' ? en : zh)[key] ?? key;
  for (const [name, value] of Object.entries(values ?? {})) result = result.replaceAll(`{${name}}`, String(value));
  return result;
}

